import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import { importLegacySentinel } from './mechbay-legacy-fixture.mjs';
import { completeInitialCampaignSetup } from './campaign-setup.mjs';
const url = process.env.E2E_URL ?? 'http://127.0.0.1:5223/';
const shots = process.env.SHOT_DIR ?? 'reports/unified-bay';
await mkdir(shots, { recursive: true });
const browser = await chromium.launch({ headless: true });
let checks = 0;
const check = (label, ok) => { if (!ok) throw new Error(label); console.log(`PASS ${++checks}: ${label}`); };
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(String(error)));
  await page.goto(url);
  await page.getByTestId('home-mechbay').click();
  await importLegacySentinel(page);
  await page.getByTestId('stock-weapon-medium_laser').focus();
  await page.keyboard.press('Enter');
  await page.getByTestId('bay-location-right_arm').locator('[data-testid^="remove-weapon-"]').first().click();
  check('removal works while holding an incompatible weapon, without controls shifting',
    await page.getByTestId('bay-undo').isEnabled() && await page.getByTestId('bay-armed').count() === 0);
  await page.getByTestId('bay-undo').click();
  await page.getByTestId('design-picker').selectOption('halberd_prime');
  check('one editing page includes weight, armour, heat and cooling controls', await page.getByTestId('bay-readiness').isVisible() && await page.getByRole('slider', { name: 'Quick armour allocation' }).isVisible() && await page.locator('[data-workspace-tab]').count() === 0);
  await page.screenshot({ path: `${shots}/halberd-unified.png` });
  // Remove heavy arm guns to make room for the exact missile configurations reported.
  for (let i = 0; i < 2; i++) await page.getByTestId('bay-location-left_arm').locator('[data-testid^="remove-weapon-"]').first().click();
  if (await page.getByRole('button', {name:'Clear filter',exact:true}).isVisible()) await page.getByRole('button', {name:'Clear filter',exact:true}).click();
  await page.getByTestId('shelf-search').fill('Longshot 20');
  const missile = page.getByTestId('stock-weapon-lrm20');
  await missile.scrollIntoViewIfNeeded();
  // Browser drag events exercise the real DataTransfer/drop handlers, without changing game state.
  const transfer = await page.evaluateHandle(() => new DataTransfer());
  await missile.dispatchEvent('dragstart', { dataTransfer: transfer });
  const torso = page.getByTestId('free-slots-right_torso');
  await torso.dispatchEvent('dragover', { dataTransfer: transfer });
  await torso.dispatchEvent('drop', { dataTransfer: transfer });
  await page.getByTestId('mechbay').dispatchEvent('dragend', { dataTransfer: transfer });
  check('Longshot drag fits the right torso and automatically supplies matching ammunition', await page.getByTestId('bay-location-right_torso').innerText().then(text => text.includes('Longshot 20')) && await page.getByTestId('ammo-supply-lrm20').innerText().then(text => text.includes('1t')));
  await page.getByTestId('add-ammo-lrm20').click();
  check('Add ammo increases the matching feed and names its storage location', await page.getByTestId('ammo-supply-lrm20').innerText().then(text => text.includes('2t') && text.includes('Torso')));
  await page.getByRole('tab', { name: 'Ammo', exact: true }).click();
  await page.getByTestId('shelf-search').fill('');
  const ammo = page.getByTestId('stock-ammo-lrm20');
  await ammo.click();
  await page.getByTestId('free-slots-right_torso').click();
  check('manual ammo placement works in the selected torso', await page.getByTestId('bay-location-right_torso').innerText().then(text => text.includes('ammo')) && await page.getByTestId('ammo-supply-lrm20').innerText().then(text => text.includes('3t')));
  await page.getByRole('tab', { name: 'Weapons', exact: true }).click();
  if (await page.getByRole('button', {name:'Clear filter',exact:true}).isVisible()) await page.getByRole('button', {name:'Clear filter',exact:true}).click();
  await page.getByTestId('shelf-search').fill('Seeker 6');
  await page.getByTestId('stock-weapon-streak_srm6').click();
  await page.getByTestId('free-slots-left_torso').click();
  check('Seeker has its own automatic matching ammunition feed', await page.getByTestId('ammo-supply-streak_srm6').innerText().then(text => text.includes('1t')));
  await page.getByTestId('add-ammo-streak_srm6').click();
  check('Seeker ammunition can be increased independently', await page.getByTestId('ammo-supply-streak_srm6').innerText().then(text => text.includes('2t')));
  await page.getByTestId('bay-readiness').scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${shots}/missile-ammunition.png` });
  check('overweight loadouts explain the exact weight blocker', await page.getByTestId('bay-save').isDisabled() && await page.getByTestId('bay-readiness').innerText().then(text => /Overweight by .*Remove/.test(text)));
  await page.getByTestId('bay-location-right_arm').locator('[data-testid^="remove-weapon-"]').first().click();
  if (await page.getByTestId('bay-save').isDisabled()) await page.getByTestId('bay-location-right_arm').locator('[data-testid^="remove-weapon-"]').first().click();
  check('removing weight restores saving', !(await page.getByTestId('bay-save').isDisabled()));
  await page.getByTestId('bay-save-as').click();
  const input = page.getByRole('dialog').locator('input');
  await input.fill('Missile Test Company');
  await page.getByRole('dialog').getByRole('button', {name:/Save/}).click();
  const saved = await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('ironline.design.')).map(key => JSON.parse(localStorage.getItem(key))).find(design => design.name === 'Missile Test Company'));
  check('named save retains both missile weapons and their ammunition', saved?.mounts.some(mount => mount.weaponId === 'lrm20') && saved.ammo.some(bin => bin.weaponId === 'streak_srm6' && bin.tons > 0));
  await page.reload(); await page.getByTestId('home-mechbay').click(); await page.getByTestId('bay-stored').selectOption(saved.id);
  check('saved configuration reloads after browser refresh', await page.getByTestId('design-name').inputValue() === 'Missile Test Company');
  check('empty legs are labelled as mobility rather than weapon grids', await page.getByTestId('bay-location-left_leg').innerText().then(text => text.includes('Mobility')) && await page.getByTestId('free-slots-left_leg').count() === 0);
  await page.getByTestId('bay-exit').click(); await page.getByTestId('home-campaign').click();
  await completeInitialCampaignSetup(page);
  check('company administration is folded away from the mission path', await page.locator('.company-tools').count() === 0 || !(await page.locator('.company-tools').getAttribute('open')));
  await page.getByTestId('camp-accept').click();
  await page.getByTestId('lance-manifest').waitFor();
  check('choosing a mission immediately opens repair and deployment preparation', await page.getByTestId('hangar-stage').isVisible());
  await page.screenshot({ path: `${shots}/mission-preparation.png` });
  await page.getByTestId('hangar-continue').click();
  check('pilots are paired within the same preparation flow', await page.getByTestId('prep-team-view').isVisible());
  check('no runtime exceptions during fitting saving and campaign preparation', errors.length === 0);
  await page.setViewportSize({width:390,height:844});
  await page.getByTestId('manifest-cancel').click(); await page.getByRole('button',{name:'Home',exact:true}).click(); await page.getByTestId('home-mechbay').click();
  await page.screenshot({path:`${shots}/mobile-bay.png`});
  check('mobile MechBay has no horizontal overflow', await page.getByTestId('mechbay').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  console.log(`${checks} checks passed`);
} finally { await browser.close(); }
