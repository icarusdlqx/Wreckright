import { readFile } from 'node:fs/promises';
import { completeInitialCampaignSetup } from './campaign-setup.mjs';

/** Own context: checkpoint, restart and failure fixtures never replace the main playthrough company. */
export async function runCampaignSaveLibraryChecks({ page, shots, check }) {
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
  const savedPage = await context.newPage();
  const errors = []; savedPage.on('pageerror', error => errors.push(error.message));
  const state = () => savedPage.evaluate(() => JSON.parse(localStorage.getItem('ironline.campaign')).state);
  const records = () => savedPage.evaluate(() => JSON.parse(localStorage.getItem('ironline.campaign.saves') ?? '{"entries":[]}').entries);
  const saveNamed = async (name) => {
    await savedPage.getByTestId('camp-save').click();
    await savedPage.getByTestId('save-name').fill(name);
    if (name === 'Before the crossing') await savedPage.screenshot({ path: `${shots}/saves-save-desktop.png` });
    await savedPage.getByTestId('save-new-checkpoint').click();
    await savedPage.getByTestId('campaign-save-dialog').waitFor({ state: 'hidden' });
  };
  // Separate legacy checkpoint fixture; no calendar controls exist in the live UI.
  const waitDay = async () => {
    await savedPage.evaluate(async () => {
      const {getCatalog}=await import('/src/schema/load.ts');
      const {advanceDays}=await import('/src/campaign/campaign.ts');
      const {saveCampaign}=await import('/src/campaign/save.ts');
      const state=JSON.parse(localStorage.getItem('ironline.campaign')).state;
      advanceDays(getCatalog(),state,1,false,false);
      saveCampaign(state);
    });
    await savedPage.reload();
    await savedPage.getByTestId('home-campaign').click();
    await savedPage.getByTestId('campaign').waitFor();
  };
  try {
    await savedPage.addInitScript(() => localStorage.setItem('ironline.muted', '1'));
    await savedPage.goto(new URL('/', page.url()).href);
    await savedPage.getByTestId('home-screen').waitFor();
    await savedPage.waitForFunction(() => { const home = document.querySelector('[data-testid="home-screen"]'); const art = home?.querySelector('img'); return home?.getAttribute('data-artwork') === 'fallback' || (art && Number(getComputedStyle(art).opacity) >= .99); });
    check('Home exposes separate Load Game and New Campaign actions', await savedPage.getByTestId('home-load-game').isVisible() && await savedPage.getByTestId('home-new-campaign').isVisible());
    await savedPage.screenshot({ path: `${shots}/saves-home-after.png` });
    await savedPage.getByTestId('home-campaign').click();
    await completeInitialCampaignSetup(savedPage);
    const first = await state();
    check('campaign Save Game and Load Game are visible without opening Company files', await savedPage.getByTestId('camp-save').isVisible() && await savedPage.getByTestId('camp-load').isVisible() && await savedPage.getByTestId('camp-files').getAttribute('open') === null);
    await savedPage.screenshot({ path: `${shots}/saves-campaign-after.png` });
    await savedPage.getByTestId('camp-save').click();
    await savedPage.keyboard.press('Escape');
    check('Escape from Save Game restores the actual Save Game launcher', await savedPage.getByTestId('camp-save').evaluate(button => button === document.activeElement));
    await savedPage.getByTestId('camp-load').click();
    await savedPage.keyboard.press('Escape');
    check('Escape from Load Game restores the actual Load Game launcher', await savedPage.getByTestId('camp-load').evaluate(button => button === document.activeElement));
    await saveNamed('Before the crossing');
    const firstRecord = (await records()).find(entry => entry.name === 'Before the crossing');
    check('a named checkpoint records the complete company without changing the autosave', JSON.stringify(JSON.parse(firstRecord.raw).state) === JSON.stringify(first) && JSON.stringify(await state()) === JSON.stringify(first));
    await waitDay();
    const later = await state();
    await saveNamed('Later preparations');
    check('a second checkpoint keeps both independent moments', (await records()).filter(entry => entry.kind === 'checkpoint').length === 2 && later.day === first.day + 1);
    await savedPage.getByTestId('camp-load').click();
    await savedPage.getByTestId(`save-entry-${firstRecord.id}`).click();
    check('selected checkpoint explains its campaign, day and fixed difficulty', (await savedPage.getByTestId('save-detail').innerText()).includes(`Day ${first.day}`) && (await savedPage.getByTestId('save-detail').innerText()).includes(first.difficulty));
    const downloadPromise = savedPage.waitForEvent('download');
    await savedPage.getByTestId('save-export-selected').click();
    const exported = await downloadPromise;
    check('selected checkpoint exports its exact original bytes', await readFile(await exported.path(), 'utf8') === firstRecord.raw);
    await savedPage.screenshot({ path: `${shots}/saves-load-desktop.png` });
    await savedPage.getByTestId('save-load-selected').click();
    await savedPage.getByTestId('campaign-save-dialog').waitFor({ state: 'hidden' });
    check('loading an earlier checkpoint restores its complete company', JSON.stringify(await state()) === JSON.stringify(first));
    check('loading keeps the complete later company in its existing named or safety record', (await records()).some(entry => JSON.stringify(JSON.parse(entry.raw).state) === JSON.stringify(later)));
    await savedPage.reload();
    await savedPage.getByTestId('home-campaign').click();
    await savedPage.getByTestId('campaign').waitFor();
    check('Continue after reload resumes the selected checkpoint', JSON.stringify(await state()) === JSON.stringify(first));
    await waitDay();
    const revised = await state();
    await savedPage.getByTestId('camp-save').click();
    await savedPage.getByTestId(`save-entry-${firstRecord.id}`).click();
    await savedPage.getByTestId('save-name').fill('Revised crossing');
    await savedPage.getByTestId('save-overwrite-selected').click();
    await savedPage.getByTestId('save-confirm-cancel').click();
    check('cancelling overwrite preserves the selected checkpoint byte for byte', (await records()).find(entry => entry.id === firstRecord.id).raw === firstRecord.raw);
    await savedPage.getByTestId('save-overwrite-selected').click();
    await savedPage.getByTestId('save-confirm').click();
    await savedPage.getByTestId('campaign-save-dialog').waitFor({ state: 'hidden' });
    check('explicit overwrite replaces only the selected named checkpoint', (await records()).find(entry => entry.id === firstRecord.id).name === 'Revised crossing' && JSON.stringify(JSON.parse((await records()).find(entry => entry.id === firstRecord.id).raw).state) === JSON.stringify(revised) && (await records()).some(entry => entry.name === 'Later preparations'));
    await savedPage.getByTestId('camp-exit').click();
    await savedPage.evaluate(() => localStorage.setItem('ironline.campaign.debriefed', '4'));
    await savedPage.getByTestId('home-new-campaign').click();
    await savedPage.getByTestId('company-card-aurelian_recall').click();
    await savedPage.getByTestId('campaign-difficulty-picker').selectOption('veteran');
    await savedPage.getByTestId('campaign-choice-start').click();
    await savedPage.getByTestId('campaign-chooser').waitFor({ state: 'hidden' });
    const newCompany = await state();
    check('a Home-created campaign resets the previous company’s viewed-report cursor', await savedPage.evaluate(() => Number(localStorage.getItem('ironline.campaign.debriefed'))) === 0);
    check('New Campaign starts the selected faction and difficulty with a fresh run', newCompany.campaignId === 'aurelian_recall' && newCompany.difficulty === 'veteran' && newCompany.seed !== first.seed);
    check('starting another faction keeps every named checkpoint and the prior company', (await records()).some(entry => JSON.parse(entry.raw).state.seed === first.seed) && (await records()).filter(entry => entry.kind === 'checkpoint').length === 2);
    await savedPage.getByTestId('camp-load').click();
    await savedPage.getByTestId(`save-entry-${firstRecord.id}`).click();
    await savedPage.getByTestId('save-load-selected').click();
    await savedPage.getByTestId('campaign-save-dialog').waitFor({ state: 'hidden' });
    check('a saved company restores its original faction and difficulty', (await state()).campaignId === first.campaignId && (await state()).difficulty === first.difficulty);
    check('switching back preserves the newly started other faction', (await records()).some(entry => JSON.parse(entry.raw).state.seed === newCompany.seed));
    await savedPage.getByTestId('camp-exit').click();
    await savedPage.evaluate(() => localStorage.setItem('ironline.campaign.debriefed', '4'));
    await savedPage.getByTestId('home-load-game').click();
    await savedPage.getByTestId(`save-entry-${firstRecord.id}`).click();
    await savedPage.getByTestId('save-load-selected').click();
    await savedPage.getByTestId('campaign').waitFor();
    check('Home Load restores the selected company without inheriting another run’s viewed reports', (await state()).campaignId === first.campaignId && await savedPage.evaluate(() => Number(localStorage.getItem('ironline.campaign.debriefed'))) === 0);
    await savedPage.getByTestId('camp-load').click();
    await savedPage.getByTestId(`save-entry-${firstRecord.id}`).click();
    await savedPage.getByTestId('save-delete-selected').click();
    await savedPage.keyboard.press('Escape');
    check('Escape cancels deletion without dismissing the library or deleting the save', await savedPage.getByTestId('campaign-save-dialog').isVisible() && (await records()).some(entry => entry.id === firstRecord.id));
    for (const width of [390, 320]) {
      await savedPage.setViewportSize({ width, height: 844 });
      await savedPage.screenshot({ path: `${shots}/saves-load-phone${width === 390 ? '' : '-320'}.png` });
      check(`${width}px saved-games panel fits horizontally and retains visible touch-sized load and close controls`, await savedPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth && ['save-load-selected', 'save-dialog-close'].every(id => { const element = document.querySelector(`[data-testid="${id}"]`); const box = element.getBoundingClientRect(); return box.height >= 44 && box.top >= 0 && box.bottom <= innerHeight && element.contains(document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2)); })));
    }
    await savedPage.setViewportSize({ width: 1440, height: 900 });
    const beforeImport = await savedPage.evaluate(() => localStorage.getItem('ironline.campaign'));
    await savedPage.getByTestId('save-import').setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{broken') });
    await savedPage.getByTestId('save-notice').waitFor();
    check('invalid import reports the error and leaves the current company intact', await savedPage.evaluate(() => localStorage.getItem('ironline.campaign')) === beforeImport && (await savedPage.getByTestId('save-notice').innerText()).includes('JSON'));
    const unknown = JSON.parse(beforeImport); unknown.state.campaignId = 'unavailable_campaign';
    await savedPage.getByTestId('save-import').setInputFiles({ name: 'unknown.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(unknown)) });
    await savedPage.waitForFunction(() => document.querySelector('[data-testid="save-notice"]')?.textContent.includes('does not contain campaign'));
    check('unknown campaign import fails locally instead of opening an invalid game route', await savedPage.evaluate(() => localStorage.getItem('ironline.campaign')) === beforeImport && await savedPage.getByTestId('campaign').isVisible());
    await savedPage.getByTestId('save-dialog-close').click();
    await savedPage.getByTestId('camp-save').click();
    await savedPage.evaluate(() => {
      window.__saveLibrarySetItem = Storage.prototype.setItem;
      Storage.prototype.setItem = function(key, value) { if (key === 'ironline.campaign.saves') throw new DOMException('Quota fixture', 'QuotaExceededError'); return window.__saveLibrarySetItem.call(this, key, value); };
    });
    const beforeFailure = await records();
    await savedPage.getByTestId('save-name').fill('Quota failure');
    await savedPage.getByTestId('save-new-checkpoint').click();
    await savedPage.getByTestId('save-notice').waitFor();
    check('quota failure keeps the active company and prior named saves', JSON.stringify(await records()) === JSON.stringify(beforeFailure) && await savedPage.evaluate(() => localStorage.getItem('ironline.campaign')) === beforeImport && (await savedPage.getByTestId('save-notice').innerText()).includes('could not be written'));
    await savedPage.evaluate(() => { Storage.prototype.setItem = window.__saveLibrarySetItem; delete window.__saveLibrarySetItem; });
    check('the complete save and recovery journey has no browser errors', errors.length === 0, errors.join(' | '));
  } catch (error) { await savedPage.screenshot({ path: `${shots}/saves-error.png` }); throw error; } finally { await context.close(); }
}
